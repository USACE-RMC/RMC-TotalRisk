using System;
using System.Collections.Generic;
using System.Linq;
using RMC.TotalRisk.Analyses.CostBenefit;
using RMC.TotalRisk.Core.Enums;
using RMC.TotalRisk.Results.Risk;
using RMC.TotalRisk.Results.LifeCycle;

namespace RMC.TotalRisk.Results.CostBenefit
{
    /// <summary>
    /// The results of a cost-benefit study: the study-convention echo block, the
    /// per-alternative economics rows (baseline first), the per-type per-stream consequence
    /// reductions, the plot-ready trajectory points, and the per-alternative life-cycle
    /// trajectories.
    /// </summary>
    /// <remarks>
    /// <para>
    ///     <b>Authors:</b>
    ///     Haden Smith, USACE Risk Management Center, cole.h.smith@usace.army.mil
    /// </para>
    /// <para>
    /// The presentation contract: every input convention that shaped a number is echoed
    /// beside the tables — rate, horizon, grid, benefit stream, headline accounting,
    /// exceedance levels, the monetization map with its vintages, the life-safety
    /// declaration, willingness to pay, the equity seats, and the do-no-harm policy — so a
    /// reviewer never reconstructs a convention from context. The deep per-alternative
    /// trajectories are runtime references regenerated by a re-run.
    /// </para>
    /// </remarks>
    public sealed class CostBenefitResults
    {
        /// <summary>
        /// Initializes a study results container.
        /// </summary>
        /// <param name="periodYears">The planning horizon in years.</param>
        /// <param name="discountRate">The annual discount rate.</param>
        /// <param name="epochGridYears">The study-wide epoch start years, ascending.</param>
        /// <param name="benefitRiskType">The stream the headline economics differenced.</param>
        /// <param name="accounting">The headline accounting convention.</param>
        /// <param name="alphaLevels">The declared exceedance levels.</param>
        /// <param name="monetization">The monetization map, or null for none.</param>
        /// <param name="lifeSafetyConsequenceType">The life-safety consequence-type position (−1 = none).</param>
        /// <param name="willingnessToPay">The willingness to pay per statistical life (NaN = none).</param>
        /// <param name="willingnessToPayVintage">The willingness-to-pay vintage echo.</param>
        /// <param name="alarpProximity">The declared tolerable-risk proximity.</param>
        /// <param name="alarpBandThresholds">The band-threshold override, or null for the regulation defaults.</param>
        /// <param name="individualRiskLimit">The individual-risk floor of the equity weighting.</param>
        /// <param name="equityExponent">The equity-versus-efficiency exponent.</param>
        /// <param name="doNoHarm">The do-no-harm policy.</param>
        /// <param name="consequenceLabels">The declared consequence-type labels (position 0 = primary).</param>
        /// <param name="consequenceUnits">The declared consequence-type units, parallel to the labels.</param>
        /// <param name="alternatives">The economics rows, the designated baseline first.</param>
        /// <param name="consequenceReductions">The per-type per-stream reduction rows.</param>
        /// <param name="trajectoryPoints">The plot-ready trajectory points.</param>
        /// <param name="trajectories">The per-alternative trajectories, parallel to the economics rows.</param>
        /// <param name="baselineIndividualRisk">The declared baseline-side individual-risk seat (NaN = the proxy is in use).</param>
        /// <param name="alternativeIndividualRisk">The declared alternative-side individual-risk seat (NaN = the proxy is in use).</param>
        /// <param name="objectives">The declared objective vector echo, or null for none recorded.</param>
        /// <param name="constraints">The declared constraint echo, or null for none recorded.</param>
        /// <param name="epsilonStudy">The declared ε-constraint study echo, or null.</param>
        /// <param name="constraintEvaluations">The declared constraints' per-alternative evaluations, or null.</param>
        /// <param name="epsilonSweep">The ε-constraint sweep results, or null when no study is declared.</param>
        /// <param name="frontier">The declared-vector frontier results, or null when not computed.</param>
        /// <param name="mcda">The multi-criteria scores, or null when no weights are declared.</param>
        /// <param name="diagnostics">The computation diagnostics, or null for none.</param>
        /// <param name="strategyRankings">The decision-strategy rankings, or null for none.</param>
        /// <param name="decisionSummary">The strategy-by-recommendation summary, or null when no ranking was computed.</param>
        /// <param name="regretMatrices">The shared-state regret analyses, or null for none.</param>
        /// <param name="epistemicMeasures">The epistemic band rows, or null for none.</param>
        /// <param name="chanceConstraints">The chance-constraint evaluations, or null for none.</param>
        /// <param name="dominance">The stochastic-dominance screen entries, or null for none.</param>
        /// <exception cref="ArgumentNullException">Thrown when a required list is null.</exception>
        /// <exception cref="ArgumentException">Thrown when the trajectories do not parallel the economics rows.</exception>
        public CostBenefitResults(int periodYears, double discountRate,
            IReadOnlyList<int> epochGridYears, RiskType benefitRiskType, LifeCycleAccounting accounting,
            IReadOnlyList<double> alphaLevels, ConsequenceMonetization? monetization,
            int lifeSafetyConsequenceType, double willingnessToPay, string willingnessToPayVintage,
            AlarpProximity alarpProximity, IReadOnlyList<double>? alarpBandThresholds,
            double individualRiskLimit, double equityExponent, DoNoHarmPolicy doNoHarm,
            IReadOnlyList<string> consequenceLabels, IReadOnlyList<string> consequenceUnits,
            IReadOnlyList<AlternativeEconomics> alternatives,
            IReadOnlyList<ConsequenceReduction> consequenceReductions,
            IReadOnlyList<TrajectoryPoint> trajectoryPoints,
            IReadOnlyList<LifeCycleRiskResults> trajectories,
            double baselineIndividualRisk = double.NaN,
            double alternativeIndividualRisk = double.NaN,
            IReadOnlyList<ObjectiveDeclaration>? objectives = null,
            IReadOnlyList<CostBenefitConstraint>? constraints = null,
            EpsilonConstraintStudy? epsilonStudy = null,
            IReadOnlyList<ConstraintEvaluation>? constraintEvaluations = null,
            EpsilonSweepResults? epsilonSweep = null,
            ParetoFrontierResults? frontier = null,
            McdaResults? mcda = null,
            IReadOnlyList<ComputationDiagnostic>? diagnostics = null,
            IReadOnlyList<StrategyRanking>? strategyRankings = null,
            DecisionSummary? decisionSummary = null,
            IReadOnlyList<RegretMatrixResults>? regretMatrices = null,
            IReadOnlyList<EpistemicMeasureSummary>? epistemicMeasures = null,
            IReadOnlyList<ChanceConstraintEntry>? chanceConstraints = null,
            IReadOnlyList<DominanceEntry>? dominance = null)
        {
            PeriodYears = periodYears;
            DiscountRate = discountRate;
            if (epochGridYears == null) throw new ArgumentNullException(nameof(epochGridYears));
            if (alphaLevels == null) throw new ArgumentNullException(nameof(alphaLevels));
            if (consequenceLabels == null) throw new ArgumentNullException(nameof(consequenceLabels));
            if (consequenceUnits == null) throw new ArgumentNullException(nameof(consequenceUnits));
            if (alternatives == null) throw new ArgumentNullException(nameof(alternatives));
            if (consequenceReductions == null) throw new ArgumentNullException(nameof(consequenceReductions));
            if (trajectoryPoints == null) throw new ArgumentNullException(nameof(trajectoryPoints));
            if (trajectories == null) throw new ArgumentNullException(nameof(trajectories));
            if (trajectories.Count != alternatives.Count)
                throw new ArgumentException("The trajectories must parallel the economics rows.", nameof(trajectories));

            EpochGridYears = Array.AsReadOnly(epochGridYears.ToArray());
            BenefitRiskType = benefitRiskType;
            Accounting = accounting;
            AlphaLevels = Array.AsReadOnly(alphaLevels.ToArray());
            Monetization = monetization;
            LifeSafetyConsequenceType = lifeSafetyConsequenceType;
            WillingnessToPay = willingnessToPay;
            WillingnessToPayVintage = willingnessToPayVintage ?? string.Empty;
            AlarpProximity = alarpProximity;
            AlarpBandThresholds = alarpBandThresholds == null
                ? null
                : Array.AsReadOnly(alarpBandThresholds.ToArray());
            IndividualRiskLimit = individualRiskLimit;
            EquityExponent = equityExponent;
            DoNoHarm = doNoHarm;
            BaselineIndividualRisk = baselineIndividualRisk;
            AlternativeIndividualRisk = alternativeIndividualRisk;
            ConsequenceLabels = Array.AsReadOnly(consequenceLabels.ToArray());
            ConsequenceUnits = Array.AsReadOnly(consequenceUnits.ToArray());
            Alternatives = Array.AsReadOnly(alternatives.ToArray());
            ConsequenceReductions = Array.AsReadOnly(consequenceReductions.ToArray());
            TrajectoryPoints = Array.AsReadOnly(trajectoryPoints.ToArray());
            Trajectories = Array.AsReadOnly(trajectories.ToArray());
            Objectives = objectives == null
                ? Array.Empty<ObjectiveDeclaration>()
                : Array.AsReadOnly(objectives.ToArray());
            Constraints = constraints == null
                ? Array.Empty<CostBenefitConstraint>()
                : Array.AsReadOnly(constraints.ToArray());
            EpsilonStudy = epsilonStudy;
            ConstraintEvaluations = constraintEvaluations == null
                ? Array.Empty<ConstraintEvaluation>()
                : Array.AsReadOnly(constraintEvaluations.ToArray());
            EpsilonSweep = epsilonSweep;
            Frontier = frontier;
            Mcda = mcda;
            Diagnostics = diagnostics == null
                ? Array.Empty<ComputationDiagnostic>()
                : Array.AsReadOnly(diagnostics.ToArray());
            StrategyRankings = strategyRankings == null
                ? Array.Empty<StrategyRanking>()
                : Array.AsReadOnly(strategyRankings.ToArray());
            Summary = decisionSummary;
            RegretMatrices = regretMatrices == null
                ? Array.Empty<RegretMatrixResults>()
                : Array.AsReadOnly(regretMatrices.ToArray());
            EpistemicMeasures = epistemicMeasures == null
                ? Array.Empty<EpistemicMeasureSummary>()
                : Array.AsReadOnly(epistemicMeasures.ToArray());
            ChanceConstraints = chanceConstraints == null
                ? Array.Empty<ChanceConstraintEntry>()
                : Array.AsReadOnly(chanceConstraints.ToArray());
            Dominance = dominance == null
                ? Array.Empty<DominanceEntry>()
                : Array.AsReadOnly(dominance.ToArray());
        }

        /// <summary>The planning horizon in years.</summary>
        public int PeriodYears { get; }

        /// <summary>The annual discount rate (0 = undiscounted).</summary>
        public double DiscountRate { get; }

        /// <summary>The study-wide epoch start years, ascending — every trajectory shares them.</summary>
        public IReadOnlyList<int> EpochGridYears { get; }

        /// <summary>The stream the headline economics differenced.</summary>
        public RiskType BenefitRiskType { get; }

        /// <summary>The headline accounting convention (both are always computed).</summary>
        public LifeCycleAccounting Accounting { get; }

        /// <summary>The declared exceedance levels.</summary>
        public IReadOnlyList<double> AlphaLevels { get; }

        /// <summary>The monetization map with its vintages, or null for none.</summary>
        public ConsequenceMonetization? Monetization { get; }

        /// <summary>The life-safety consequence-type position (−1 = none declared).</summary>
        public int LifeSafetyConsequenceType { get; }

        /// <summary>The willingness to pay per statistical life (NaN = none declared).</summary>
        public double WillingnessToPay { get; }

        /// <summary>The willingness-to-pay vintage echo.</summary>
        public string WillingnessToPayVintage { get; }

        /// <summary>The declared tolerable-risk proximity.</summary>
        public AlarpProximity AlarpProximity { get; }

        /// <summary>The band-threshold override, or null for the regulation defaults.</summary>
        public IReadOnlyList<double>? AlarpBandThresholds { get; }

        /// <summary>The individual-risk floor of the equity weighting.</summary>
        public double IndividualRiskLimit { get; }

        /// <summary>The equity-versus-efficiency exponent.</summary>
        public double EquityExponent { get; }

        /// <summary>
        /// The declared baseline-side individual-risk seat; NaN when the survival-equivalent
        /// annualized failure-probability proxy is in use (the rows echo the values used).
        /// </summary>
        public double BaselineIndividualRisk { get; }

        /// <summary>
        /// The declared alternative-side individual-risk seat; NaN when each row's own proxy
        /// is in use.
        /// </summary>
        public double AlternativeIndividualRisk { get; }

        /// <summary>The do-no-harm policy.</summary>
        public DoNoHarmPolicy DoNoHarm { get; }

        /// <summary>The declared consequence-type labels (position 0 = primary).</summary>
        public IReadOnlyList<string> ConsequenceLabels { get; }

        /// <summary>The declared consequence-type units, parallel to the labels.</summary>
        public IReadOnlyList<string> ConsequenceUnits { get; }

        /// <summary>The economics rows, the designated baseline first.</summary>
        public IReadOnlyList<AlternativeEconomics> Alternatives { get; }

        /// <summary>The per-type per-stream reduction rows, grouped by alternative.</summary>
        public IReadOnlyList<ConsequenceReduction> ConsequenceReductions { get; }

        /// <summary>The plot-ready trajectory points, grouped by alternative in epoch order.</summary>
        public IReadOnlyList<TrajectoryPoint> TrajectoryPoints { get; }

        /// <summary>
        /// The per-alternative life-cycle trajectories, parallel to the economics rows —
        /// runtime references regenerated by a re-run. Alternatives that shared one system
        /// and plan share one trajectory instance.
        /// </summary>
        public IReadOnlyList<LifeCycleRiskResults> Trajectories { get; }

        /// <summary>The declared objective vector echo.</summary>
        public IReadOnlyList<ObjectiveDeclaration> Objectives { get; }

        /// <summary>The declared constraint echo.</summary>
        public IReadOnlyList<CostBenefitConstraint> Constraints { get; }

        /// <summary>The declared ε-constraint study echo, or null when none is declared.</summary>
        public EpsilonConstraintStudy? EpsilonStudy { get; }

        /// <summary>
        /// The declared constraints' per-alternative evaluations, parallel to the constraint
        /// echo — a declared constraint is never silently inert.
        /// </summary>
        public IReadOnlyList<ConstraintEvaluation> ConstraintEvaluations { get; }

        /// <summary>The ε-constraint sweep results, or null when no study is declared.</summary>
        public EpsilonSweepResults? EpsilonSweep { get; }

        /// <summary>The declared-vector frontier with its projections and incremental table, or null.</summary>
        public ParetoFrontierResults? Frontier { get; }

        /// <summary>The multi-criteria scores, or null when no weights are declared.</summary>
        public McdaResults? Mcda { get; }

        /// <summary>The computation diagnostics (named skips and exclusions).</summary>
        public IReadOnlyList<ComputationDiagnostic> Diagnostics { get; }

        /// <summary>The decision-strategy rankings, in catalog order.</summary>
        public IReadOnlyList<StrategyRanking> StrategyRankings { get; }

        /// <summary>The strategy-by-recommendation summary, or null when no ranking was computed.</summary>
        public DecisionSummary? Summary { get; }

        /// <summary>The shared-state regret analyses, one per aligned decision criterion.</summary>
        public IReadOnlyList<RegretMatrixResults> RegretMatrices { get; }

        /// <summary>The epistemic band rows, one per alternative and decision criterion.</summary>
        public IReadOnlyList<EpistemicMeasureSummary> EpistemicMeasures { get; }

        /// <summary>The chance-constraint evaluations, one per evaluable declared constraint.</summary>
        public IReadOnlyList<ChanceConstraintEntry> ChanceConstraints { get; }

        /// <summary>The stochastic-dominance screen entries.</summary>
        public IReadOnlyList<DominanceEntry> Dominance { get; }
    }
}
